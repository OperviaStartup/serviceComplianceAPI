ALTER TABLE obligations ADD COLUMN source_plan_id BIGINT REFERENCES service_plans(id);
ALTER TABLE obligations ADD COLUMN source_definition_id BIGINT REFERENCES obligation_definitions(id);
ALTER TABLE obligations ADD COLUMN occurrence_date DATE;
ALTER TABLE obligations ADD COLUMN timezone VARCHAR(64);
ALTER TABLE obligations ADD COLUMN assignment_version BIGINT NOT NULL DEFAULT 0;

ALTER TABLE obligations ADD CONSTRAINT ck_generated_obligation_source
    CHECK ((source_plan_id IS NULL AND source_definition_id IS NULL AND occurrence_date IS NULL)
        OR (source_plan_id IS NOT NULL AND source_definition_id IS NOT NULL AND occurrence_date IS NOT NULL));
ALTER TABLE obligations ADD CONSTRAINT ck_generated_obligation_timezone
    CHECK (timezone IS NULL OR timezone = 'America/Lima');
CREATE UNIQUE INDEX uq_obligation_definition_occurrence
    ON obligations(source_definition_id, occurrence_date)
    WHERE source_definition_id IS NOT NULL AND occurrence_date IS NOT NULL;

CREATE TABLE obligation_assignment_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obligation_id BIGINT NOT NULL REFERENCES obligations(id) ON DELETE CASCADE,
    previous_operator_id BIGINT REFERENCES users(id),
    new_operator_id BIGINT NOT NULL REFERENCES users(id),
    actor_id BIGINT NOT NULL REFERENCES users(id),
    assigned_at TIMESTAMP WITH TIME ZONE NOT NULL,
    reason VARCHAR(2000) NOT NULL
);
CREATE INDEX idx_obligation_assignment_history_obligation
    ON obligation_assignment_history(obligation_id, assigned_at, id);
