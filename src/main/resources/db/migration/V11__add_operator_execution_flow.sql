-- Existing results stay historical; no start/submission time is invented for them.
ALTER TABLE executions ALTER COLUMN result DROP NOT NULL;
ALTER TABLE executions ADD COLUMN state VARCHAR(30) NOT NULL DEFAULT 'LEGACY';
ALTER TABLE executions ADD COLUMN started_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE executions ADD COLUMN submitted_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE executions ADD COLUMN updated_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE executions ADD COLUMN version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE executions ADD COLUMN completed_steps INTEGER NOT NULL DEFAULT 0;
ALTER TABLE executions ADD COLUMN attached_photos INTEGER NOT NULL DEFAULT 0;
ALTER TABLE executions ADD COLUMN exception_count INTEGER NOT NULL DEFAULT 0;
ALTER TABLE executions ADD CONSTRAINT ck_execution_lifecycle CHECK (
    (state = 'LEGACY' AND result IS NOT NULL AND started_at IS NULL) OR
    (state = 'IN_PROGRESS' AND started_at IS NOT NULL AND submitted_at IS NULL AND result IS NULL) OR
    (state = 'SUBMITTED' AND started_at IS NOT NULL AND submitted_at IS NOT NULL
     AND submitted_at >= started_at AND result IS NOT NULL AND result = 'COMPLETED'));
ALTER TABLE executions ADD CONSTRAINT ck_execution_counters CHECK
    (version >= 0 AND completed_steps >= 0 AND attached_photos >= 0 AND exception_count >= 0);
CREATE UNIQUE INDEX uq_field_execution_obligation ON executions(obligation_id) WHERE state <> 'LEGACY';

CREATE TABLE execution_step_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    execution_id BIGINT NOT NULL REFERENCES executions(id) ON DELETE CASCADE,
    step_id BIGINT NOT NULL REFERENCES obligation_steps(id),
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE(execution_id, step_id)
);
CREATE TABLE operational_exceptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    execution_id BIGINT NOT NULL REFERENCES executions(id) ON DELETE CASCADE,
    step_id BIGINT REFERENCES obligation_steps(id),
    reason VARCHAR(50) NOT NULL CHECK (reason IN ('AREA_CLOSED','MISSING_SUPPLIES','SAFETY_RISK','OTHER')),
    description VARCHAR(2000) NOT NULL,
    reported_by BIGINT NOT NULL REFERENCES users(id),
    reported_at TIMESTAMP WITH TIME ZONE NOT NULL,
    operation_id UUID NOT NULL,
    UNIQUE(execution_id, operation_id)
);
ALTER TABLE evidences ALTER COLUMN url DROP NOT NULL;
ALTER TABLE evidences ADD COLUMN photo_requirement_id BIGINT REFERENCES obligation_photo_requirements(id);
ALTER TABLE evidences ADD COLUMN storage_key VARCHAR(500);
ALTER TABLE evidences ADD COLUMN content_type VARCHAR(30);
ALTER TABLE evidences ADD COLUMN file_size BIGINT;
ALTER TABLE evidences ADD COLUMN checksum VARCHAR(64);
ALTER TABLE evidences ADD COLUMN captured_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE evidences ADD CONSTRAINT uq_execution_photo_requirement UNIQUE(execution_id, photo_requirement_id);
ALTER TABLE evidences ADD CONSTRAINT ck_managed_photo CHECK (photo_requirement_id IS NULL OR
    (type = 'PHOTO' AND storage_key IS NOT NULL AND length(storage_key) > 0
     AND content_type IS NOT NULL AND content_type IN ('image/jpeg','image/png')
     AND file_size IS NOT NULL AND file_size > 0 AND file_size <= 5242880
     AND checksum IS NOT NULL AND checksum ~ '^[0-9a-f]{64}$' AND url IS NULL));
