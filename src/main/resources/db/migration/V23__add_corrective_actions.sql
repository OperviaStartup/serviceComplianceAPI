CREATE TABLE corrective_actions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compliance_case_id BIGINT NOT NULL REFERENCES compliance_cases(id),
    source_compliance_result_id BIGINT NOT NULL,
    company_id BIGINT NOT NULL,
    site_id BIGINT NOT NULL,
    assignee_id BIGINT NOT NULL REFERENCES users(id),
    description VARCHAR(4000) NOT NULL,
    target_date DATE NOT NULL,
    timezone VARCHAR(64) NOT NULL DEFAULT 'America/Lima',
    state VARCHAR(30) NOT NULL CHECK (state IN ('ASSIGNED','ATTENTION_SUBMITTED','RETURNED','CLOSED')),
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by BIGINT NOT NULL REFERENCES users(id),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    closed_by BIGINT REFERENCES users(id),
    closed_at TIMESTAMP WITH TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    CONSTRAINT fk_corrective_action_result
        FOREIGN KEY (source_compliance_result_id, compliance_case_id)
        REFERENCES compliance_results(id, compliance_case_id),
    CONSTRAINT fk_corrective_action_scope
        FOREIGN KEY (site_id, company_id) REFERENCES sites(id, company_id),
    CONSTRAINT ck_corrective_action_timezone CHECK (timezone = 'America/Lima'),
    CONSTRAINT ck_corrective_action_closed CHECK (
        (state = 'CLOSED' AND closed_by IS NOT NULL AND closed_at IS NOT NULL)
        OR (state <> 'CLOSED' AND closed_by IS NULL AND closed_at IS NULL)
    )
);

CREATE TABLE corrective_action_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    corrective_action_id BIGINT NOT NULL REFERENCES corrective_actions(id),
    action_version BIGINT NOT NULL CHECK (action_version >= 0),
    from_state VARCHAR(30) CHECK (from_state IN ('ASSIGNED','ATTENTION_SUBMITTED','RETURNED','CLOSED')),
    to_state VARCHAR(30) NOT NULL CHECK (to_state IN ('ASSIGNED','ATTENTION_SUBMITTED','RETURNED','CLOSED')),
    actor_id BIGINT NOT NULL REFERENCES users(id),
    reason VARCHAR(2000) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_corrective_action_event_version UNIQUE (corrective_action_id, action_version),
    CONSTRAINT ck_corrective_action_event_transition CHECK (
        (action_version = 0 AND from_state IS NULL AND to_state = 'ASSIGNED')
        OR (action_version > 0 AND (
            (from_state = 'ASSIGNED' AND to_state = 'ATTENTION_SUBMITTED')
            OR (from_state = 'RETURNED' AND to_state = 'ATTENTION_SUBMITTED')
            OR (from_state = 'ATTENTION_SUBMITTED' AND to_state IN ('RETURNED','CLOSED'))
        ))
    )
);

CREATE INDEX idx_corrective_actions_case ON corrective_actions(compliance_case_id, id);
CREATE INDEX idx_corrective_actions_assignee
    ON corrective_actions(company_id, site_id, assignee_id, state, target_date, id);
