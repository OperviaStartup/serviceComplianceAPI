CREATE TABLE client_observations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compliance_case_id BIGINT NOT NULL REFERENCES compliance_cases(id),
    series_id UUID NOT NULL,
    revision INTEGER NOT NULL CHECK (revision > 0),
    supersedes_observation_id BIGINT,
    description VARCHAR(4000) NOT NULL CHECK (length(trim(description)) > 0),
    origin VARCHAR(30) NOT NULL CHECK (origin IN ('EMAIL','PHONE','SITE_VISIT','OTHER')),
    observed_date DATE NOT NULL,
    amendment_reason VARCHAR(1000),
    recorded_by BIGINT NOT NULL REFERENCES users(id),
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_client_observation_revision UNIQUE (series_id, revision),
    CONSTRAINT uq_client_observation_identity UNIQUE (id, series_id, compliance_case_id),
    CONSTRAINT uq_client_observation_case_identity UNIQUE (id, compliance_case_id),
    CONSTRAINT fk_client_observation_predecessor
        FOREIGN KEY (supersedes_observation_id, series_id, compliance_case_id)
        REFERENCES client_observations(id, series_id, compliance_case_id),
    CONSTRAINT ck_client_observation_amendment CHECK (
        (revision = 1 AND supersedes_observation_id IS NULL AND amendment_reason IS NULL)
        OR (revision > 1 AND supersedes_observation_id IS NOT NULL
            AND amendment_reason IS NOT NULL AND length(trim(amendment_reason)) > 0)
    )
);

ALTER TABLE compliance_results ADD COLUMN source_observation_id BIGINT;
ALTER TABLE compliance_results
    ADD CONSTRAINT fk_compliance_result_observation
    FOREIGN KEY (source_observation_id, compliance_case_id)
    REFERENCES client_observations(id, compliance_case_id);
ALTER TABLE compliance_results
    ADD CONSTRAINT uq_compliance_result_observation UNIQUE (source_observation_id);

CREATE INDEX idx_client_observations_case
    ON client_observations(compliance_case_id, recorded_at, id);
