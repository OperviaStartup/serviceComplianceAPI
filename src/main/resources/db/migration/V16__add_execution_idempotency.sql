CREATE TABLE execution_idempotency (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    actor_id BIGINT NOT NULL REFERENCES users(id),
    command VARCHAR(80) NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    execution_id BIGINT NOT NULL REFERENCES executions(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_execution_idempotency_scope
        UNIQUE (company_id, actor_id, command, idempotency_key)
);

CREATE INDEX idx_execution_idempotency_expiry ON execution_idempotency(expires_at);
CREATE INDEX idx_execution_idempotency_execution ON execution_idempotency(execution_id);
