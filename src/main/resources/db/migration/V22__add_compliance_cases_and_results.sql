CREATE TABLE compliance_cases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obligation_id BIGINT NOT NULL UNIQUE REFERENCES obligations(id),
    company_id BIGINT NOT NULL,
    site_id BIGINT NOT NULL,
    decision_version BIGINT NOT NULL DEFAULT 0 CHECK (decision_version >= 0),
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_compliance_case_scope FOREIGN KEY (site_id, company_id) REFERENCES sites(id, company_id)
);

CREATE TABLE compliance_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compliance_case_id BIGINT NOT NULL REFERENCES compliance_cases(id),
    execution_id BIGINT NOT NULL REFERENCES executions(id),
    decision_version BIGINT NOT NULL CHECK (decision_version > 0),
    predecessor_result_id BIGINT,
    outcome VARCHAR(30) NOT NULL CHECK (outcome IN ('COMPLIANT','EXCEPTION_ACCEPTED','NON_COMPLIANT')),
    source_review_version VARCHAR(100) NOT NULL,
    source_execution_version BIGINT NOT NULL CHECK (source_execution_version >= 0),
    source_plan_id BIGINT REFERENCES service_plans(id),
    source_plan_version INTEGER,
    source_definition_id BIGINT REFERENCES obligation_definitions(id),
    source_definition_version BIGINT,
    explanation VARCHAR(4000) NOT NULL,
    reevaluation_reason VARCHAR(2000),
    decided_by BIGINT NOT NULL REFERENCES users(id),
    decided_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_compliance_result_version UNIQUE (compliance_case_id, decision_version),
    CONSTRAINT uq_compliance_result_case_identity UNIQUE (id, compliance_case_id),
    CONSTRAINT fk_compliance_result_predecessor
        FOREIGN KEY (predecessor_result_id, compliance_case_id)
        REFERENCES compliance_results(id, compliance_case_id),
    CONSTRAINT ck_compliance_result_predecessor CHECK (
        (decision_version = 1 AND predecessor_result_id IS NULL AND reevaluation_reason IS NULL)
        OR (decision_version > 1 AND predecessor_result_id IS NOT NULL
            AND reevaluation_reason IS NOT NULL AND length(trim(reevaluation_reason)) > 0)
    ),
    CONSTRAINT ck_compliance_result_plan_snapshot CHECK (
        (source_plan_id IS NULL AND source_plan_version IS NULL)
        OR (source_plan_id IS NOT NULL AND source_plan_version IS NOT NULL)
    ),
    CONSTRAINT ck_compliance_result_definition_snapshot CHECK (
        (source_definition_id IS NULL AND source_definition_version IS NULL)
        OR (source_definition_id IS NOT NULL AND source_definition_version IS NOT NULL)
    )
);

CREATE TABLE compliance_result_criteria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compliance_result_id BIGINT NOT NULL REFERENCES compliance_results(id),
    position INTEGER NOT NULL CHECK (position > 0),
    code VARCHAR(100) NOT NULL,
    status VARCHAR(30) NOT NULL CHECK (status IN ('PASS','FAIL','NOT_APPLICABLE')),
    notes VARCHAR(2000),
    CONSTRAINT uq_compliance_result_criterion UNIQUE (compliance_result_id, code),
    CONSTRAINT uq_compliance_result_criterion_position UNIQUE (compliance_result_id, position)
);

CREATE TABLE compliance_result_findings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compliance_result_id BIGINT NOT NULL REFERENCES compliance_results(id),
    position INTEGER NOT NULL CHECK (position > 0),
    code VARCHAR(100) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    operational_exception_id BIGINT REFERENCES operational_exceptions(id),
    exception_disposition VARCHAR(30) CHECK (exception_disposition IN ('ACCEPTED','REJECTED')),
    CONSTRAINT uq_compliance_result_finding_position UNIQUE (compliance_result_id, position),
    CONSTRAINT ck_compliance_finding_exception CHECK (
        (operational_exception_id IS NULL AND exception_disposition IS NULL)
        OR (operational_exception_id IS NOT NULL AND exception_disposition IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uq_compliance_finding_exception
    ON compliance_result_findings(compliance_result_id, operational_exception_id)
    WHERE operational_exception_id IS NOT NULL;
CREATE INDEX idx_compliance_results_execution ON compliance_results(execution_id);
