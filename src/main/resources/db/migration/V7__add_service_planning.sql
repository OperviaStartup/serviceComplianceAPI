CREATE TABLE service_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    service_id BIGINT NOT NULL,
    site_id BIGINT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    timezone VARCHAR(64) NOT NULL,
    state VARCHAR(30) NOT NULL,
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_service_plans_period CHECK (end_date >= start_date),
    CONSTRAINT ck_service_plans_timezone CHECK (timezone = 'America/Lima'),
    CONSTRAINT ck_service_plans_state CHECK (state IN ('DRAFT')),
    CONSTRAINT fk_service_plan_service_company FOREIGN KEY (service_id, company_id)
        REFERENCES company_services(id, company_id),
    CONSTRAINT fk_service_plan_site_company FOREIGN KEY (site_id, company_id)
        REFERENCES sites(id, company_id)
);

CREATE INDEX idx_service_plans_company_site_service
    ON service_plans(company_id, site_id, service_id);

CREATE TABLE service_plan_idempotency (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    actor_id BIGINT NOT NULL REFERENCES users(id),
    operation VARCHAR(80) NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    service_plan_id BIGINT NOT NULL REFERENCES service_plans(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_service_plan_idempotency_scope
        UNIQUE (company_id, actor_id, operation, idempotency_key)
);

CREATE INDEX idx_service_plan_idempotency_expiry ON service_plan_idempotency(expires_at);
