ALTER TABLE operational_exceptions
    ADD CONSTRAINT uq_operational_exception_execution UNIQUE (id, execution_id);

ALTER TABLE evidences
    ADD CONSTRAINT uq_evidence_execution UNIQUE (id, execution_id);

CREATE TABLE operational_exception_evidence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exception_id BIGINT NOT NULL,
    evidence_id BIGINT NOT NULL,
    execution_id BIGINT NOT NULL,
    CONSTRAINT uq_operational_exception_evidence UNIQUE (exception_id, evidence_id),
    CONSTRAINT fk_exception_evidence_exception
        FOREIGN KEY (exception_id, execution_id)
        REFERENCES operational_exceptions(id, execution_id) ON DELETE CASCADE,
    CONSTRAINT fk_exception_evidence_evidence
        FOREIGN KEY (evidence_id, execution_id)
        REFERENCES evidences(id, execution_id)
);

CREATE INDEX idx_exception_evidence_execution
    ON operational_exception_evidence(execution_id);
