CREATE TABLE corrective_action_submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    corrective_action_id BIGINT NOT NULL REFERENCES corrective_actions(id),
    submission_number INTEGER NOT NULL CHECK (submission_number > 0),
    action_version BIGINT NOT NULL CHECK (action_version > 0),
    details VARCHAR(2000) NOT NULL CHECK (length(trim(details)) > 0),
    submitted_by BIGINT NOT NULL REFERENCES users(id),
    submitted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_corrective_submission_number UNIQUE (corrective_action_id, submission_number),
    CONSTRAINT uq_corrective_submission_action_version UNIQUE (corrective_action_id, action_version),
    CONSTRAINT uq_corrective_submission_identity UNIQUE (id, corrective_action_id)
);

CREATE TABLE corrective_action_evidence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT NOT NULL,
    corrective_action_id BIGINT NOT NULL,
    evidence_order INTEGER NOT NULL CHECK (evidence_order BETWEEN 1 AND 5),
    storage_key VARCHAR(500) NOT NULL UNIQUE,
    content_type VARCHAR(30) NOT NULL CHECK (content_type IN ('image/jpeg','image/png')),
    file_size BIGINT NOT NULL CHECK (file_size > 0 AND file_size <= 5242880),
    checksum VARCHAR(64) NOT NULL CHECK (length(checksum) = 64),
    captured_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_corrective_evidence_submission
        FOREIGN KEY (submission_id, corrective_action_id)
        REFERENCES corrective_action_submissions(id, corrective_action_id),
    CONSTRAINT uq_corrective_evidence_order UNIQUE (submission_id, evidence_order)
);

CREATE TABLE corrective_attention_idempotency (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    actor_id BIGINT NOT NULL REFERENCES users(id),
    command VARCHAR(80) NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    request_hash VARCHAR(64) NOT NULL CHECK (length(request_hash) = 64),
    submission_id BIGINT NOT NULL REFERENCES corrective_action_submissions(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_corrective_attention_idempotency_scope
        UNIQUE (company_id, actor_id, command, idempotency_key),
    CONSTRAINT ck_corrective_attention_expiry CHECK (expires_at > created_at)
);

CREATE INDEX idx_corrective_submissions_action
    ON corrective_action_submissions(corrective_action_id, submission_number);
CREATE INDEX idx_corrective_evidence_action
    ON corrective_action_evidence(corrective_action_id, submission_id, evidence_order);
CREATE INDEX idx_corrective_attention_idempotency_expiry
    ON corrective_attention_idempotency(expires_at);
