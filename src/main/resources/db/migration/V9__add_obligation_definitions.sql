ALTER TABLE service_plans DROP CONSTRAINT ck_service_plans_state;
ALTER TABLE service_plans ADD CONSTRAINT ck_service_plans_state CHECK (state IN ('DRAFT', 'ACTIVE'));

CREATE TABLE obligation_definitions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_plan_id BIGINT NOT NULL REFERENCES service_plans(id) ON DELETE CASCADE,
    site_id BIGINT NOT NULL REFERENCES sites(id), activity VARCHAR(255) NOT NULL,
    instructions VARCHAR(2000) NOT NULL, acceptance_criteria VARCHAR(2000) NOT NULL,
    recurrence_type VARCHAR(20) NOT NULL, occurrence_date DATE,
    recurrence_interval INTEGER NOT NULL, local_start_time TIME NOT NULL,
    window_duration_minutes INTEGER NOT NULL, timezone VARCHAR(64) NOT NULL,
    created_by BIGINT NOT NULL REFERENCES users(id), updated_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_definition_recurrence CHECK (recurrence_type IN ('ONCE','DAILY','WEEKLY')),
    CONSTRAINT ck_definition_interval CHECK (recurrence_interval BETWEEN 1 AND 30),
    CONSTRAINT ck_definition_window CHECK (window_duration_minutes BETWEEN 1 AND 1440),
    CONSTRAINT ck_definition_timezone CHECK (timezone = 'America/Lima')
);

CREATE TABLE obligation_definition_weekdays (
    definition_id BIGINT NOT NULL REFERENCES obligation_definitions(id) ON DELETE CASCADE,
    day_of_week VARCHAR(10) NOT NULL,
    PRIMARY KEY (definition_id, day_of_week)
);

CREATE TABLE evidence_requirements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    definition_id BIGINT NOT NULL REFERENCES obligation_definitions(id) ON DELETE CASCADE,
    evidence_type VARCHAR(30) NOT NULL, is_required BOOLEAN NOT NULL,
    minimum_count INTEGER NOT NULL, maximum_count INTEGER NOT NULL,
    CONSTRAINT ck_evidence_requirement_type CHECK (evidence_type IN ('PHOTO','QR_CODE','LOCATION','SIGNATURE')),
    CONSTRAINT ck_evidence_requirement_count CHECK
        (minimum_count >= 0 AND maximum_count BETWEEN 1 AND 10 AND maximum_count >= minimum_count)
);

CREATE TABLE evidence_requirement_constraints (
    evidence_requirement_id BIGINT NOT NULL REFERENCES evidence_requirements(id) ON DELETE CASCADE,
    constraint_key VARCHAR(50) NOT NULL, constraint_value VARCHAR(255) NOT NULL,
    PRIMARY KEY (evidence_requirement_id, constraint_key)
);

CREATE INDEX idx_obligation_definitions_plan ON obligation_definitions(service_plan_id);
