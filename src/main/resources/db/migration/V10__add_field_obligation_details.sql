-- Preserve existing obligations: their start time and execution instructions are unknown.
ALTER TABLE obligations ADD COLUMN starts_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE obligations ADD CONSTRAINT ck_obligation_execution_window
    CHECK (starts_at IS NULL OR due_at > starts_at);

CREATE TABLE obligation_steps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obligation_id BIGINT NOT NULL REFERENCES obligations(id) ON DELETE CASCADE,
    title VARCHAR(255) NOT NULL,
    instructions VARCHAR(2000),
    step_order INTEGER NOT NULL CHECK (step_order > 0),
    CONSTRAINT uq_obligation_step_order UNIQUE (obligation_id, step_order)
);

CREATE TABLE obligation_photo_requirements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obligation_id BIGINT NOT NULL REFERENCES obligations(id) ON DELETE CASCADE,
    title VARCHAR(255) NOT NULL,
    description VARCHAR(2000),
    photo_order INTEGER NOT NULL CHECK (photo_order > 0),
    CONSTRAINT uq_obligation_photo_order UNIQUE (obligation_id, photo_order)
);
