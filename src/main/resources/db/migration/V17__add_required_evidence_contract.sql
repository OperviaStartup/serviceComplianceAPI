CREATE TABLE obligation_evidence_requirements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obligation_id BIGINT NOT NULL REFERENCES obligations(id) ON DELETE CASCADE,
    source_requirement_id BIGINT NOT NULL,
    evidence_type VARCHAR(30) NOT NULL,
    is_required BOOLEAN NOT NULL,
    minimum_count INTEGER NOT NULL,
    maximum_count INTEGER NOT NULL,
    requirement_order INTEGER NOT NULL,
    CONSTRAINT ck_obligation_evidence_type
        CHECK (evidence_type IN ('PHOTO','QR_CODE','LOCATION','SIGNATURE')),
    CONSTRAINT ck_obligation_evidence_count
        CHECK (minimum_count >= 0 AND maximum_count BETWEEN 1 AND 10 AND maximum_count >= minimum_count),
    CONSTRAINT uq_obligation_evidence_order UNIQUE (obligation_id, requirement_order)
);

CREATE TABLE obligation_evidence_requirement_constraints (
    obligation_evidence_requirement_id BIGINT NOT NULL
        REFERENCES obligation_evidence_requirements(id) ON DELETE CASCADE,
    constraint_key VARCHAR(50) NOT NULL,
    constraint_value VARCHAR(255) NOT NULL,
    PRIMARY KEY (obligation_evidence_requirement_id, constraint_key)
);

ALTER TABLE evidences ADD COLUMN evidence_requirement_id BIGINT
    REFERENCES obligation_evidence_requirements(id);
ALTER TABLE evidences ADD COLUMN created_by BIGINT REFERENCES users(id);
ALTER TABLE evidences ADD COLUMN text_value VARCHAR(512);
ALTER TABLE evidences ADD COLUMN latitude NUMERIC(9,6);
ALTER TABLE evidences ADD COLUMN longitude NUMERIC(9,6);
ALTER TABLE evidences ADD COLUMN accuracy_meters NUMERIC(10,2);
ALTER TABLE evidences ADD CONSTRAINT ck_required_evidence_payload CHECK (
    evidence_requirement_id IS NULL OR
    (created_by IS NOT NULL AND captured_at IS NOT NULL AND file_size IS NOT NULL
        AND checksum IS NOT NULL AND checksum ~ '^[0-9a-f]{64}$' AND (
        (type = 'PHOTO' AND storage_key IS NOT NULL AND content_type IS NOT NULL
            AND content_type IN ('image/jpeg','image/png') AND file_size BETWEEN 1 AND 5242880
            AND text_value IS NULL) OR
        (type = 'SIGNATURE' AND storage_key IS NOT NULL AND content_type = 'image/png'
            AND file_size BETWEEN 1 AND 1048576 AND text_value IS NULL) OR
        (type = 'QR_CODE' AND storage_key IS NULL AND text_value IS NOT NULL
            AND file_size > 0 AND length(text_value) BETWEEN 1 AND 512
            AND latitude IS NULL AND longitude IS NULL AND accuracy_meters IS NULL) OR
        (type = 'LOCATION' AND storage_key IS NULL AND text_value IS NULL AND file_size > 0
            AND latitude IS NOT NULL AND longitude IS NOT NULL AND accuracy_meters IS NOT NULL
            AND latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180
            AND accuracy_meters > 0)
    ))
);

CREATE INDEX idx_evidence_execution_requirement
    ON evidences(execution_id, evidence_requirement_id);

CREATE TABLE evidence_idempotency (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    actor_id BIGINT NOT NULL REFERENCES users(id),
    command VARCHAR(80) NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    evidence_id BIGINT NOT NULL REFERENCES evidences(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_evidence_idempotency_scope
        UNIQUE (company_id, actor_id, command, idempotency_key)
);

CREATE INDEX idx_evidence_idempotency_expiry ON evidence_idempotency(expires_at);
