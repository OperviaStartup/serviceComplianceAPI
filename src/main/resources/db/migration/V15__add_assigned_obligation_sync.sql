CREATE TABLE obligation_assignment_changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    site_id BIGINT NOT NULL,
    operator_id BIGINT NOT NULL,
    obligation_id BIGINT NOT NULL,
    change_type VARCHAR(20) NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_obligation_assignment_change_type CHECK (change_type IN ('UPSERT', 'REMOVED'))
);

CREATE INDEX idx_obligation_assignment_changes_sync
    ON obligation_assignment_changes(company_id, site_id, operator_id, id);

CREATE OR REPLACE FUNCTION record_obligation_assignment_change()
RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP = 'INSERT' AND NEW.assigned_operator_id IS NOT NULL THEN
        INSERT INTO obligation_assignment_changes
            (company_id, site_id, operator_id, obligation_id, change_type)
        VALUES
            (NEW.company_id, NEW.site_id, NEW.assigned_operator_id, NEW.id, 'UPSERT');
    ELSIF TG_OP = 'UPDATE' THEN
        IF OLD.assigned_operator_id IS DISTINCT FROM NEW.assigned_operator_id THEN
            IF OLD.assigned_operator_id IS NOT NULL THEN
                INSERT INTO obligation_assignment_changes
                    (company_id, site_id, operator_id, obligation_id, change_type)
                VALUES
                    (OLD.company_id, OLD.site_id, OLD.assigned_operator_id, OLD.id, 'REMOVED');
            END IF;
            IF NEW.assigned_operator_id IS NOT NULL THEN
                INSERT INTO obligation_assignment_changes
                    (company_id, site_id, operator_id, obligation_id, change_type)
                VALUES
                    (NEW.company_id, NEW.site_id, NEW.assigned_operator_id, NEW.id, 'UPSERT');
            END IF;
        ELSIF OLD.status IS DISTINCT FROM NEW.status AND NEW.assigned_operator_id IS NOT NULL THEN
            INSERT INTO obligation_assignment_changes
                (company_id, site_id, operator_id, obligation_id, change_type)
            VALUES
                (NEW.company_id, NEW.site_id, NEW.assigned_operator_id, NEW.id, 'UPSERT');
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_obligation_assignment_changes
AFTER INSERT OR UPDATE OF assigned_operator_id, status ON obligations
FOR EACH ROW EXECUTE FUNCTION record_obligation_assignment_change();
