CREATE TABLE offline_sync_operations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    actor_id BIGINT NOT NULL REFERENCES users(id),
    client_operation_id UUID NOT NULL,
    operation_type VARCHAR(40) NOT NULL CHECK (operation_type IN
        ('START_EXECUTION','UPDATE_STEP','ATTACH_EVIDENCE','REPORT_EXCEPTION','SUBMIT_EXECUTION')),
    request_hash VARCHAR(64) NOT NULL,
    outcome VARCHAR(30) NOT NULL CHECK (outcome IN ('SYNCED','REQUIRES_ATTENTION')),
    result_code VARCHAR(80) NOT NULL,
    resource_type VARCHAR(30),
    resource_id BIGINT,
    current_version BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_offline_sync_operation_scope
        UNIQUE (company_id, actor_id, client_operation_id),
    CONSTRAINT ck_offline_sync_resource CHECK (
        (resource_type IS NULL AND resource_id IS NULL) OR
        (resource_type IN ('EXECUTION','EVIDENCE','EXCEPTION') AND resource_id IS NOT NULL)),
    CONSTRAINT ck_offline_sync_version CHECK (current_version IS NULL OR current_version >= 0)
);

CREATE INDEX idx_offline_sync_expiry ON offline_sync_operations(expires_at);
CREATE INDEX idx_offline_sync_actor_created
    ON offline_sync_operations(company_id, actor_id, created_at, id);
