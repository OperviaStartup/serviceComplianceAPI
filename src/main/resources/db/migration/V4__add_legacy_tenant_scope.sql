CREATE TABLE sites (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, company_id BIGINT NOT NULL REFERENCES companies(id), name VARCHAR(255) NOT NULL, UNIQUE (id, company_id));
